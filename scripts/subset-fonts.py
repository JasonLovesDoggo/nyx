#!/usr/bin/env python3
"""Generate the committed JetBrains Mono subsets; see static/fonts/README.md."""
from pathlib import Path
from shutil import copyfile
import json
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'node_modules/@fontsource/jetbrains-mono/files'
OUT = ROOT / 'static/fonts'
CORE = set(range(0x20, 0x7f)) | {0xa0, 0xa9, 0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2026}

package = SOURCE.parent
version = json.loads((package / 'package.json').read_text())['version']
if version != '5.2.8':
    raise RuntimeError(f'Review the font and update this script for version {version}')
OUT.mkdir(parents=True, exist_ok=True)
copyfile(package / 'LICENSE', OUT / 'OFL.txt')

def ranges(chars):
    chars = sorted(chars)
    groups = []
    start = end = chars[0]
    for char in chars[1:]:
        if char == end + 1:
            end = char
        else:
            groups.append((start, end)); start = end = char
    groups.append((start, end))
    return ', '.join(f'U+{a:04X}' + (f'-{b:04X}' if b != a else '') for a, b in groups)

css = ['/* Generated by scripts/subset-fonts.py. Do not edit. */']
for weight in (400, 700):
    source = SOURCE / f'jetbrains-mono-latin-{weight}-normal.woff2'
    # Preserve the original WOFF fallback for browsers without WOFF2 support.
    fallback = f'jetbrains-mono-latin-{weight}-normal.woff'
    copyfile(SOURCE / fallback, OUT / fallback)
    original = TTFont(source, recalcTimestamp=False)
    cmap = set(original.getBestCmap())
    for part, chars in [('core', cmap & CORE), ('extended', cmap - CORE)]:
        font = TTFont(source, recalcTimestamp=False)
        opts = subset.Options()
        opts.flavor = 'woff2'
        opts.hinting = True
        # Keep default shaping and contextual ligatures; the site does not enable fractions.
        opts.layout_features = ['calt', 'ccmp', 'locl', 'mark']
        sub = subset.Subsetter(options=opts)
        sub.populate(unicodes=chars)
        sub.subset(font)
        filename = f'jetbrains-mono-{weight}-{part}.woff2'
        font.save(OUT / filename)
        actual = set(TTFont(OUT / filename).getBestCmap())
        if actual != chars:
            raise RuntimeError(f'{filename}: unexpected cmap')
        css.append(f"""@font-face {{
  font-family: 'JetBrains Mono';
  font-style: normal;
  font-display: swap;
  font-weight: {weight};
  src: url('/fonts/{filename}') format('woff2'), url('/fonts/{fallback}') format('woff');
  unicode-range: {ranges(actual)};
}}""")
(OUT / 'fonts.css').write_text('\n'.join(css) + '\n')
